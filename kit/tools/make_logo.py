#!/usr/bin/env python3
"""
make_logo.py - turn a transparent image (PNG / WebP) into a JavaScript module an app can draw
with fillRect runs, since the kit has no image decoder and build.py ships no image files.

    python3 kit/tools/make_logo.py docs/media/perea_logo.png --width 180 --out apps/mhd_flex/logo.js
        [--opacity 0.6] [--ink 40] [--levels 4] [--palette 24]

The image is cropped to the bounding box of its alpha, scaled to --width (LANCZOS), its alpha
quantised to --levels steps and multiplied by --opacity (a "subtle" logo bakes its opacity here:
the kit's cv.alpha() is not applied to layer blits). Colours are reduced to at most --palette
entries; pixels whose brightest channel is at or below --ink are one entry flagged `ink`, which the
app paints in the theme's text colour (black ink would vanish on the dark themes).

Output:  module.exports = { w, h, palette: ['#rrggbbaa', ...], ink: <index or -1>, runs: [[y, x, w, pi], ...] }
Each run is one row's stretch of one palette entry. The module is rejected over 60 KB.
"""
import argparse
import sys
from collections import Counter

from PIL import Image

ap = argparse.ArgumentParser()
ap.add_argument('image')
ap.add_argument('--width', type=int, default=180)
ap.add_argument('--out', required=True)
ap.add_argument('--opacity', type=float, default=0.6)
ap.add_argument('--ink', type=int, default=40, help='max channel value that counts as ink (text colour at runtime)')
ap.add_argument('--levels', type=int, default=4, help='alpha steps')
ap.add_argument('--palette', type=int, default=24, help='max colours (ink aside)')
a = ap.parse_args()

im = Image.open(a.image).convert('RGBA')
bbox = im.getchannel('A').getbbox()
if not bbox:
    sys.exit('the image is fully transparent')
im = im.crop(bbox)
h = max(1, round(im.height * a.width / im.width))
im = im.resize((a.width, h), Image.LANCZOS)

# colours: median-cut on the opaque pixels, ink aside
rgb = Image.new('RGB', im.size)
pixels = list(getattr(im, 'get_flattened_data', im.getdata)())
rgb.putdata([(r, g, b) for r, g, b, _ in pixels])
quant = rgb.quantize(colors=a.palette, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
qpal = quant.getpalette()[:a.palette * 3]
qidx = list(getattr(quant, 'get_flattened_data', quant.getdata)())

step = 255 / a.levels
entries = {}            # (r, g, b, alpha) -> palette index; ink entries keyed ('ink', alpha)
palette = []
ink_index = -1
grid = []
for i, (r, g, b, al) in enumerate(pixels):
    lvl = round(al / step)
    if lvl <= 0:
        grid.append(-1)
        continue
    alpha = min(255, round(lvl * step * a.opacity))
    if max(r, g, b) <= a.ink:
        key = ('ink', alpha)
    else:
        q = qidx[i]
        key = (qpal[3 * q], qpal[3 * q + 1], qpal[3 * q + 2], alpha)
    if key not in entries:
        entries[key] = len(palette)
        palette.append(key)
    grid.append(entries[key])

# runs per row
runs = []
for y in range(h):
    x = 0
    while x < a.width:
        p = grid[y * a.width + x]
        if p < 0:
            x += 1
            continue
        x0 = x
        while x < a.width and grid[y * a.width + x] == p:
            x += 1
        runs.append((y, x0, x - x0, p))

def css(e):
    if e[0] == 'ink':
        return '#000000%02x' % e[1]
    return '#%02x%02x%02x%02x' % e

inks = [i for i, e in enumerate(palette) if e[0] == 'ink']
lines = ["'use strict';",
         '// Generated by kit/tools/make_logo.py from %s (%d px wide, opacity %g): do not edit.' % (a.image.replace('\\', '/'), a.width, a.opacity),
         '// palette entries listed in `ink` carry only an alpha: the app paints them in the theme text colour.',
         'module.exports = {',
         '    w: %d, h: %d,' % (a.width, h),
         '    palette: [%s],' % ', '.join("'%s'" % css(e) for e in palette),
         '    ink: [%s],' % ', '.join(str(i) for i in inks),
         '    runs: [']
for i in range(0, len(runs), 24):
    lines.append('        ' + ','.join('[%d,%d,%d,%d]' % r for r in runs[i:i + 24]) + ',')
lines += ['    ],', '};', '']
text = '\n'.join(lines)
if len(text) > 60 * 1024:
    sys.exit('module would be %d bytes (over 60 KB): lower --width or --palette' % len(text))
with open(a.out, 'w', encoding='utf-8') as f:
    f.write(text)
print('%s: %dx%d, %d colours (%d ink), %d runs, %d bytes' % (a.out, a.width, h, len(palette), len(inks), len(runs), len(text)))
